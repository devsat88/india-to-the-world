// Turns India's official state boundaries into small SVG paths for the map page.
// Source: DataMeet's States/Admin2 layer (CC BY 4.0), updated in 2021 to the
// Survey of India's map: 28 states and 8 union territories, with all of Jammu
// & Kashmir and Ladakh. The national outline is drawn from the same shapes.
//   node scripts/india-map.mjs   (rewrites lib/india-outline.ts)
import fs from 'node:fs';
import path from 'node:path';

// Pinned to a commit, so a rerun draws the same map.
const COMMIT = '2c0c306a0c786a83876065a62b7b82646d8a639d';
const SOURCE = `https://raw.githubusercontent.com/datameet/maps/${COMMIT}/States/Admin2`;
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');

// Equirectangular at India's middle latitude; the same numbers place the markers.
const BOX = { west: 68, east: 97.5, south: 6.5, north: 37.2 };
const K = Math.cos((22 * Math.PI) / 180);
const WIDTH = 1000;
const S = WIDTH / ((BOX.east - BOX.west) * K);
const HEIGHT = Math.round((BOX.north - BOX.south) * S);
const project = ([lon, lat]) => [(lon - BOX.west) * K * S, (BOX.north - lat) * S];

/** Polygon records from a .shp and their names from the matching .dbf. */
function readShapes(shp, dbf) {
  const rings = [];
  for (let o = 100; o < shp.length; ) {
    const c = o + 8;
    if (shp.readInt32LE(c) === 5) {
      const np = shp.readInt32LE(c + 36), n = shp.readInt32LE(c + 40), pts = c + 44 + np * 4;
      const parts = Array.from({ length: np }, (_, i) => shp.readInt32LE(c + 44 + i * 4));
      rings.push(parts.map((s, i) => Array.from({ length: (parts[i + 1] ?? n) - s }, (_, k) => [shp.readDoubleLE(pts + (s + k) * 16), shp.readDoubleLE(pts + (s + k) * 16 + 8)])));
    } else rings.push([]);
    o = c + shp.readInt32BE(o + 4) * 2;
  }
  const count = dbf.readInt32LE(4), header = dbf.readInt16LE(8), size = dbf.readInt16LE(10), width = dbf[32 + 16];
  const names = Array.from({ length: count }, (_, r) => dbf.toString('utf8', header + r * size + 1, header + r * size + 1 + width).trim());
  return names.map((name, i) => ({ name, rings: rings[i] }));
}

// Douglas-Peucker in screen pixels.
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a], [bx, by] = pts[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    let far = -1, max = tol;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len;
      if (d > max) { max = d; far = i; }
    }
    if (far > 0) { keep[far] = 1; stack.push([a, far], [far, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

async function get(ext) {
  const r = await fetch(`${SOURCE}.${ext}`);
  if (!r.ok) throw new Error(`${SOURCE}.${ext}: HTTP ${r.status}`);
  return Buffer.from(await r.arrayBuffer());
}
const states = readShapes(await get('shp'), await get('dbf'));
let points = 0;
// Island territories keep every island; elsewhere specks under a pixel are dropped.
const ISLANDS = new Set(['Andaman & Nicobar', 'Lakshadweep']);
const span = (px) => Math.max(Math.max(...px.map((p) => p[0])) - Math.min(...px.map((p) => p[0])), Math.max(...px.map((p) => p[1])) - Math.min(...px.map((p) => p[1])));
const paths = states.map(({ name, rings }) => {
  const d = rings
    .map((ring) => {
      const px = ring.map(project);
      if (span(px) < (ISLANDS.has(name) ? 0.3 : 1.5)) return '';
      // A ring starts and ends on the same point, so it is simplified as two halves.
      const mid = px.length >> 1;
      let out = [...simplify(px.slice(0, mid + 1), 0.8).slice(0, -1), ...simplify(px.slice(mid), 0.8)];
      if (out.length < 4) out = px.filter((_, i) => i % Math.ceil(px.length / 6) === 0);
      if (out.length < 3) return '';
      points += out.length;
      return `M${out.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join('L')}Z`;
    })
    .join('');
  return { name, d };
});

const out = `// Generated by scripts/india-map.mjs from ${SOURCE}.shp
// (DataMeet, CC BY 4.0), which follows the Survey of India's official map. Don't edit.
export const MAP = { width: ${WIDTH}, height: ${HEIGHT}, west: ${BOX.west}, north: ${BOX.north}, k: ${K}, scale: ${S} };

export const STATES: { name: string; d: string }[] = ${JSON.stringify(paths.sort((a, b) => a.name.localeCompare(b.name)), null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};
`;
fs.writeFileSync(path.join(root, 'lib/india-outline.ts'), out);
console.log(`ok    ${states.length} states and union territories, ${points} points, ${(out.length / 1024).toFixed(0)} KB -> lib/india-outline.ts`);
